-- Всяка цел трябва да е видима по целия път до корена.
DO $$
DECLARE n INT;
BEGIN
    WITH RECURSIVE up AS (
        SELECT DISTINCT m.to_category AS target, c.id, c.parent_id, c.show_flag
        FROM move_56 m JOIN categories c ON c.id = m.to_category
        UNION ALL
        SELECT up.target, c.id, c.parent_id, c.show_flag FROM up JOIN categories c ON c.id = up.parent_id)
    SELECT count(DISTINCT target) INTO n FROM up WHERE NOT show_flag;
    IF n > 0 THEN
        RAISE EXCEPTION 'ПРЕКЪСНАТО: % целеви категории не са видими.', n;
    END IF;
    IF (SELECT count(*) FROM move_56) <> 67 THEN
        RAISE EXCEPTION 'ПРЕКЪСНАТО: списъкът трябва да има 67 продукта.';
    END IF;
END $$;

UPDATE products p
SET category_id_pre_phase5 = coalesce(p.category_id_pre_phase5, p.category_id),
    category_id            = m.to_category,
    manually_categorized   = TRUE,
    updated_at             = NOW()
FROM move_56 m
WHERE p.id = m.product_id AND p.category_id = m.from_category;

DO $$
DECLARE moved INT; skipped INT;
BEGIN
    SELECT count(*) INTO moved FROM move_56 m JOIN products p ON p.id = m.product_id AND p.category_id = m.to_category;
    skipped := 67 - moved;
    RAISE NOTICE 'Скрипт 56: преместени % от 67 продукта; % не бяха в очакваната категория и не са пипани.', moved, skipped;
END $$;

