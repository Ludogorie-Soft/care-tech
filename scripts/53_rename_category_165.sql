-- ============================================================================
-- 53_rename_category_165.sql
--
-- Преименува категория 165 от „Защитни фолиа / стъкла за телефони" на
-- „Защитни фолиа и стъкла".
--
-- ПОВОД: скрипт 52 слага в 165 и протектори за таблети (6 фолиа ACER) и за
--        конзоли (3 протектора NACON за Nintendo Switch). Името „…за телефони"
--        стана по-тясно от съдържанието.
--
-- ⚠️ ТОВА Е ЕДИНСТВЕНИЯТ СКРИПТ ОТ ФАЗА 5, КОЙТО ПИПА `categories`.
--    Скрипт 52 пипа само `products.category_id`. Тук се сменят ДВЕ текстови
--    полета на ЕДИН ред. Не се създават, трият или местят категории;
--    parent_id, sort_order, show_flag и slug остават непокътнати.
--
-- ⚠️ КОДЪТ И БАЗАТА ТРЯБВА ДА СЪВПАДАТ. Две места държат името ТВЪРДО
--    КОДИРАНО и търсят категорията ПО ИМЕ:
--
--      1) CategoryReorganizationService:683 (VALI_SUBCATEGORIES)
--         `reorganizeValiCategories` търси по нормализирано българско име и
--         СЪЗДАВА категорията, ако не я намери. Тоест при разминаване между
--         кода и базата — В КОЯТО И ДА Е ПОСОКА — ендпойнтът POST /reorganize
--         създава ДУБЛИКАТ: видим, празен, VALI, под същия родител.
--         → Правилото не е „кодът пръв" или „скриптът пръв", а:
--           НЕ викай POST /reorganize между двете стъпки. Ендпойнтът е ръчен
--           (не е в cron), така че прозорецът е безопасен, ако никой не го пипне.
--
--      2) MostSyncService:124-125 (overrides „protect film" и „screen protector")
--         Те сочеха „Аксесоари за лаптопи/таблети" — затова 6-те фолиа ACER
--         изобщо бяха там. Пренасочени са към новото име, за да не връща
--         следващият MOST прогон новите протектори обратно в кат. 47.
--         Разминаването тук НЕ е разрушително, само временно:
--           • код нов + база стара → MostSyncService:986 не намира категорията,
--             логва warn и прескача продукта до пускането на скрипта;
--           • база нова + код стар → новите протектори пак отиват в кат. 47.
--
-- SLUG НЕ СЕ ПИПА: `screen-protector-for-mobile-phone` се ползва за рутиране
--    (`GET /categories/slug/{slug}`). Смяната му би счупила съществуващи URL-и
--    и е SEO решение, не езиково. Затова остава разминат с името — съзнателно.
--
-- ЧИСТ SQL — без psql meta-команди, работи и в GUI клиент.
--
-- Дата: 2026-09-21
-- ============================================================================

SET lock_timeout = '10s';
SET idle_in_transaction_session_timeout = '60s';
SET statement_timeout = '60s';


-- ─── СЕКЦИЯ A: отчет ПРЕДИ ──────────────────────────────────────────────────

SELECT c.id, c.name_bg, c.name_en, c.slug, c.platform, c.parent_id, c.sort_order,
       c.show_flag,
       (SELECT count(*) FROM products p WHERE p.category_id = c.id) AS produkti_sega
FROM categories c
WHERE c.id = 165;


BEGIN;

-- ─── СЕКЦИЯ B: предпазител ──────────────────────────────────────────────────
-- Спира, ако категорията не е тази, която очакваме — за да не преименуваме
-- нещо друго, ако id-тата се разминат между средите.

DO $$
DECLARE
    v_name_bg text;
BEGIN
    SELECT name_bg INTO v_name_bg FROM categories WHERE id = 165;

    IF v_name_bg IS NULL THEN
        RAISE EXCEPTION 'ПРЕКЪСНАТО: категория 165 не съществува.';
    END IF;

    IF v_name_bg <> 'Защитни фолиа / стъкла за телефони'
       AND v_name_bg <> 'Защитни фолиа и стъкла' THEN
        RAISE EXCEPTION 'ПРЕКЪСНАТО: категория 165 се казва "%", а не очакваното име. Провери преди да продължиш.', v_name_bg;
    END IF;

    IF v_name_bg = 'Защитни фолиа и стъкла' THEN
        RAISE NOTICE 'Категория 165 вече е преименувана — скриптът е идемпотентен, нищо няма да се промени.';
    END IF;
END $$;


-- ─── СЕКЦИЯ C: преименуването ───────────────────────────────────────────────

UPDATE categories
SET name_bg    = 'Защитни фолиа и стъкла',
    name_en    = 'Screen protectors',
    updated_at = NOW()
WHERE id = 165
  AND (name_bg <> 'Защитни фолиа и стъкла' OR name_en <> 'Screen protectors');


-- ─── СЕКЦИЯ D: предпазител СЛЕД ─────────────────────────────────────────────

DO $$
DECLARE
    v_broi int;
BEGIN
    SELECT count(*) INTO v_broi FROM categories
     WHERE id = 165 AND name_bg = 'Защитни фолиа и стъкла' AND name_en = 'Screen protectors';
    IF v_broi <> 1 THEN
        RAISE EXCEPTION 'ПРЕКЪСНАТО: преименуването не се получи.';
    END IF;

    -- Никоя друга категория да не носи старото или новото име (дубликат)
    SELECT count(*) INTO v_broi FROM categories
     WHERE id <> 165
       AND name_bg IN ('Защитни фолиа и стъкла', 'Защитни фолиа / стъкла за телефони');
    IF v_broi > 0 THEN
        RAISE EXCEPTION 'ПРЕКЪСНАТО: намерени са % други категории със същото име — вероятно вече е създаден дубликат.', v_broi;
    END IF;

    RAISE NOTICE '✓ Категория 165 е преименувана на „Защитни фолиа и стъкла".';
END $$;

COMMIT;


-- ─── СЕКЦИЯ E: отчет СЛЕД ───────────────────────────────────────────────────

SELECT c.id, c.name_bg, c.name_en, c.slug,
       (SELECT count(*) FROM products p WHERE p.category_id = c.id) AS produkti
FROM categories c
WHERE c.id = 165;


