-- Keyed by normalized parameter name only, so they do not depend on synced data and are safe in
-- Flyway. Taken from the parameter names on visible products in production (2026-09-24).
--   HIDE   — logistics, packaging and identifiers: never a filter, never shown in specifications.
--   IGNORE — real product information, shown in specifications but useless as a filter
--            (warranty, weight, overall dimensions, operating environment).
-- Names that only look similar but are real attributes are deliberately absent: "максимално
-- поддържано тегло", "размери на вентилатора", "брой пакети памети", "интерфейс serial ata".

